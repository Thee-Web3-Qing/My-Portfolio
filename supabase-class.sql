create table if not exists public.class_registrations (
  id uuid primary key default gen_random_uuid(),
  full_name text not null,
  whatsapp text not null,
  email text,
  reason text not null,
  reason_category text not null default 'Other',
  mentorship_interest text not null default 'Not answered',
  receipt_path text not null,
  receipt_name text not null,
  receipt_size integer not null,
  receipt_hash text,
  fraud_score integer not null default 0,
  fraud_status text not null default 'review',
  fraud_checks jsonb not null default '{}'::jsonb,
  payment_status text not null default 'pending',
  student_access_code text,
  approved_at timestamptz,
  created_at timestamptz not null default now()
);

alter table public.class_registrations add column if not exists receipt_hash text;
alter table public.class_registrations add column if not exists fraud_score integer not null default 0;
alter table public.class_registrations add column if not exists fraud_status text not null default 'review';
alter table public.class_registrations add column if not exists fraud_checks jsonb not null default '{}'::jsonb;
alter table public.class_registrations add column if not exists student_access_code text;
alter table public.class_registrations add column if not exists approved_at timestamptz;

alter table public.class_registrations enable row level security;

drop policy if exists "Anyone can submit a class registration" on public.class_registrations;
create policy "Anyone can submit a class registration"
on public.class_registrations for insert
to anon, authenticated
with check (
  char_length(full_name) between 3 and 120
  and char_length(whatsapp) between 10 and 20
  and char_length(reason) between 20 and 2000
  and receipt_size > 0
  and receipt_size <= 10485760
  and char_length(receipt_hash) = 64
  and fraud_score between 0 and 100
  and fraud_status in ('passed', 'review')
  and payment_status = 'pending'
);

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('class-receipts', 'class-receipts', false, 10485760, array['application/pdf', 'image/jpeg', 'image/png', 'image/heic', 'image/heif', 'image/webp'])
on conflict (id) do update set
  public = false,
  file_size_limit = 10485760,
  allowed_mime_types = array['application/pdf', 'image/jpeg', 'image/png', 'image/heic', 'image/heif', 'image/webp'];

drop policy if exists "Anyone can upload a class receipt PDF" on storage.objects;
drop policy if exists "Anyone can upload a class receipt file" on storage.objects;
create policy "Anyone can upload a class receipt file"
on storage.objects for insert
to anon, authenticated
with check (
  bucket_id = 'class-receipts'
  and (storage.foldername(name))[1] = 'receipts'
  and lower(storage.extension(name)) in ('pdf', 'jpg', 'jpeg', 'png', 'heic', 'heif', 'webp')
);

create index if not exists class_registrations_created_at_idx
on public.class_registrations (created_at desc);

create index if not exists class_registrations_category_idx
on public.class_registrations (reason_category);

create unique index if not exists class_registrations_receipt_hash_idx
on public.class_registrations (receipt_hash)
where receipt_hash is not null;

create table if not exists public.class_lessons (
  id bigint generated by default as identity primary key,
  lesson_number integer not null unique,
  title text not null,
  summary text not null,
  assignment_title text not null,
  assignment_prompt text not null,
  submission_type text not null default 'commit',
  deadline_days integer not null default 7,
  video_url text,
  is_published boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.class_submissions (
  id uuid primary key default gen_random_uuid(),
  registration_id uuid not null references public.class_registrations(id) on delete cascade,
  lesson_id bigint not null references public.class_lessons(id) on delete cascade,
  repository_url text,
  commit_url text,
  notes text,
  status text not null default 'pending',
  feedback text,
  submitted_at timestamptz not null default now(),
  reviewed_at timestamptz,
  unique (registration_id, lesson_id)
);

alter table public.class_lessons enable row level security;
alter table public.class_submissions enable row level security;

