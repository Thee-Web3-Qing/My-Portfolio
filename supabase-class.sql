create or replace function public.get_student_classroom(p_whatsapp text, p_code text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_registration public.class_registrations;
  v_lessons jsonb;
begin
  select * into v_registration
  from public.class_registrations
  where right(regexp_replace(whatsapp, '[^0-9]', '', 'g'), 10) = right(regexp_replace(p_whatsapp, '[^0-9]', '', 'g'), 10)
    and upper(student_access_code) = upper(trim(p_code))
    and payment_status = 'confirmed'
  limit 1;

  if v_registration.id is null then
    raise exception 'ACCESS_DENIED';
  end if;

  select coalesce(jsonb_agg(lesson_data order by lesson_number), '[]'::jsonb)
  into v_lessons
  from (
    select
      l.lesson_number,
      jsonb_build_object(
        'id', l.id,
        'lessonNumber', l.lesson_number,
        'title', l.title,
        'summary', l.summary,
        'assignmentTitle', l.assignment_title,
        'assignmentPrompt', l.assignment_prompt,
        'submissionType', l.submission_type,
        'deadlineDays', l.deadline_days,
        'videoUrl', l.video_url,
        'locked', case
          when l.lesson_number = 1 then false
          else not exists (
            select 1 from public.class_submissions previous_submission
            join public.class_lessons previous_lesson on previous_lesson.id = previous_submission.lesson_id
            where previous_submission.registration_id = v_registration.id
              and previous_lesson.lesson_number = l.lesson_number - 1
              and previous_submission.status = 'passed'
          )
        end,
        'submission', (
          select jsonb_build_object(
            'id', s.id,
            'repositoryUrl', s.repository_url,
            'commitUrl', s.commit_url,
            'notes', s.notes,
            'status', s.status,
            'feedback', s.feedback,
            'submittedAt', s.submitted_at,
            'reviewedAt', s.reviewed_at
          )
          from public.class_submissions s
          where s.registration_id = v_registration.id and s.lesson_id = l.id
        )
      ) as lesson_data
    from public.class_lessons l
    where l.is_published = true
  ) lessons;

  return jsonb_build_object(
    'student', jsonb_build_object('id', v_registration.id, 'name', v_registration.full_name),
    'classStarts', '2026-10-01',
    'lessons', v_lessons
  );
end;
$$;

create or replace function public.submit_class_assignment(
  p_whatsapp text,
  p_code text,
  p_lesson_id bigint,
  p_repository_url text,
  p_commit_url text,
  p_notes text default null
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_registration public.class_registrations;
  v_lesson public.class_lessons;
begin
  select * into v_registration
  from public.class_registrations
  where right(regexp_replace(whatsapp, '[^0-9]', '', 'g'), 10) = right(regexp_replace(p_whatsapp, '[^0-9]', '', 'g'), 10)
    and upper(student_access_code) = upper(trim(p_code))
    and payment_status = 'confirmed'
  limit 1;

  if v_registration.id is null then raise exception 'ACCESS_DENIED'; end if;

  select * into v_lesson from public.class_lessons where id = p_lesson_id and is_published = true;
  if v_lesson.id is null then raise exception 'LESSON_NOT_FOUND'; end if;

  if v_lesson.lesson_number > 1 and not exists (
    select 1 from public.class_submissions s
    join public.class_lessons l on l.id = s.lesson_id
    where s.registration_id = v_registration.id
      and l.lesson_number = v_lesson.lesson_number - 1
      and s.status = 'passed'
  ) then raise exception 'LESSON_LOCKED'; end if;

  if p_repository_url is null or p_repository_url !~* '^https://github[.]com/' then
    raise exception 'VALID_GITHUB_REPOSITORY_REQUIRED';
  end if;
  if v_lesson.submission_type = 'commit' and (p_commit_url is null or p_commit_url !~* '^https://github[.]com/.+/commit/[a-f0-9]+') then
    raise exception 'VALID_GITHUB_COMMIT_REQUIRED';
  end if;

  insert into public.class_submissions
    (registration_id, lesson_id, repository_url, commit_url, notes, status, feedback, submitted_at, reviewed_at)
  values
    (v_registration.id, v_lesson.id, trim(p_repository_url), nullif(trim(p_commit_url), ''), nullif(trim(p_notes), ''), 'pending', null, now(), null)
  on conflict (registration_id, lesson_id) do update set
    repository_url = excluded.repository_url,
    commit_url = excluded.commit_url,
    notes = excluded.notes,
    status = 'pending',
    feedback = null,
    submitted_at = now(),
    reviewed_at = null
  where public.class_submissions.status <> 'passed';

  return public.get_student_classroom(p_whatsapp, p_code);
end;
$$;

revoke all on function public.get_student_classroom(text, text) from public;
revoke all on function public.submit_class_assignment(text, text, bigint, text, text, text) from public;
grant execute on function public.get_student_classroom(text, text) to anon, authenticated;
grant execute on function public.submit_class_assignment(text, text, bigint, text, text, text) to anon, authenticated;
